#!/usr/bin/env python3
"""Phase 8: assemble the upload set for Artificial Intelligence Review and prove that it compiles on its own.

    python3 scripts/32_submission_package.py           # check build: author-item boxes still shown
    python3 scripts/32_submission_package.py --final   # submission build: fails while any \\pending/\\tbd remains

Follows the Springer Nature LaTeX authoring template user manual (v3.1, December 2024):
  * stylistically neutral: the 'journal-look' block of main.tex (custom fonts, restyled headings, smaller reference
    font) is removed, because the manual asks authors to "refrain from using custom fonts" and not to add formatting;
    keywords are given comma-separated as in the template;
  * image files at the same level as the .tex file (no subfolders), one input file per figure;
  * single line spacing (the [referee] option was not used: authors' decision, 17 Nov 2026).

Writes ../Submission_Package/ (next to SLR_Workspace):
    LaTeX_source/           flat folder to upload: main.tex, main.bbl, references.bib, included_studies.bib,
                            sn-jnl.cls, sn-basic.bst, fig01_*.pdf ... fig11_*.pdf
    Supplementary_Material/ S1-S6 (uploaded as separate supplementary files)
    main.pdf                compiled from LaTeX_source alone
    FILE_LIST.md            what each file is
The package is compiled in a fresh temporary copy; a failure is reported with the first LaTeX error.
"""
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

W = Path(__file__).resolve().parent.parent
M = W / "manuscript"
OUT = W.parent / "Submission_Package"
SRC = OUT / "LaTeX_source"
FINAL = "--final" in sys.argv

tex = (M / "main.tex").read_text()
tex = tex[tex.index("\\documentclass"):]                      # drop the internal header notes
tex, n = re.subn(r"%% BEGIN journal-look.*?%% END journal-look[^\n]*\n", "", tex, flags=re.S)
assert n == 1, "journal-look block not found"
tex = re.sub(r"\\keywords\{([^}]*)\}", lambda m: "\\keywords{" + m.group(1).replace(" $\\cdot$ ", ", ") + "}", tex)
tex = re.sub(r"\\graphicspath\{\{figures/\}\}[^\n]*\n", "", tex)      # figures sit next to main.tex
# Numbers in the text: the workspace copy uses ~1,000 \nXxx macros generated by scripts/21_text_numbers.py (traceability).
# The upload/Overleaf copy gets the values written into the text, and the definition block and the
# "%% BEGIN/END GENERATED" markers are removed, so that the source reads as plain LaTeX.
blk = re.search(r"%% BEGIN GENERATED text_numbers\n(.*?)%% END GENERATED text_numbers\n", tex, re.S)
NUM = dict(re.findall(r"\\newcommand\{\\(n[A-Za-z]+)\}\{([^}]*)\}", blk.group(1)))
tex = tex[:blk.start()] + tex[blk.end():]
tex = re.sub(r"\\(n[A-Z][A-Za-z]*)(\{\})?(?![A-Za-z])", lambda m: NUM[m.group(1)] if m.group(1) in NUM else m.group(0), tex)
tex = re.sub(r"%% (BEGIN|END) GENERATED [^\n]*\n", "", tex)
assert not re.search(r"\\n[A-Z][A-Za-z]*(?![A-Za-z])", tex[tex.index("\\begin{document}"):]), "unexpanded number macro"
# Keep the preamble to the template plus what the tables need: drop the drafting aid for author items (author items
# become plain "[TBD]" text for the authors to replace), the float-placement settings and \raggedbottom.
tex, k = re.subn(r"%% ---- Drafting aid: author items -+\n.*?%% -+\n", "", tex, flags=re.S)
assert k == 1, "drafting-aid block not found"
tex = tex.replace("\\tbd", "[TBD]")
assert "\\pending" not in tex[tex.index("\\begin{document}"):], "a [PENDING] box is still in the text"
tex = re.sub(r"\\renewcommand\{\\(top|bottom|text|floatpage)fraction\}\{[^}]*\}\n", "", tex)
tex = re.sub(r"\\setcounter\{(top|bottom|total)number\}\{\d+\}\n", "", tex)
tex = re.sub(r"\n{3,}", "\n\n", tex)
# Preamble exactly as in the template sample (sn-article.tex, v3.1 December 2024), with the reference style used by
# this journal (sn-basic, author-year) and one addition the tables need (tabularx and two column types).
PREAMBLE = r"""%Version 3.1 December 2024
% See section 11 of the User Manual for version history
%
\documentclass[pdflatex,sn-basic]{sn-jnl}% Basic Springer Nature Reference Style/Chemistry Reference Style

\usepackage{graphicx}%
\usepackage{multirow}%
\usepackage{amsmath,amssymb,amsfonts}%
\usepackage{amsthm}%
\usepackage{mathrsfs}%
\usepackage[title]{appendix}%
\usepackage{xcolor}%
\usepackage{textcomp}%
\usepackage{manyfoot}%
\usepackage{booktabs}%
\usepackage{algorithm}%
\usepackage{algorithmicx}%
\usepackage{algpseudocode}%
\usepackage{listings}%

%% Added for this manuscript: tables with wrapping columns
\usepackage{tabularx}%
\newcolumntype{L}{>{\raggedright\arraybackslash}X}%
\newcolumntype{P}[1]{>{\raggedright\arraybackslash}p{#1}}%

\theoremstyle{thmstyleone}%
\newtheorem{theorem}{Theorem}%  meant for continuous numbers
\newtheorem{proposition}[theorem]{Proposition}%
\theoremstyle{thmstyletwo}%
\newtheorem{example}{Example}%
\newtheorem{remark}{Remark}%
\theoremstyle{thmstylethree}%
\newtheorem{definition}{Definition}%

\raggedbottom

"""
tex = PREAMBLE + tex[tex.index("\\begin{document}"):]
if FINAL:
    left = re.findall(r"\[TBD\]|\[First\]|\[Second\]|\[Author\]|\[Department\]|\[Institution\]|corresponding@email", tex)
    if left:
        sys.exit(f"FINAL build refused: author items still open: {sorted(set(left))}")
figs = sorted(set(re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex)))

if OUT.exists():
    shutil.rmtree(OUT)
SRC.mkdir(parents=True)
(SRC / "main.tex").write_text(tex)
for f in ("references.bib", "included_studies.bib", "sn-jnl.cls", "sn-basic.bst"):
    shutil.copy2(M / f, SRC / f)
for f in figs:
    shutil.copy2(M / "figures" / (f if f.endswith(".pdf") else f + ".pdf"), SRC)
shutil.copytree(M / "supplementary", OUT / "Supplementary_Material",
                ignore=shutil.ignore_patterns("*.aux", "*.log", "*.fls", "*.fdb_latexmk", "*.synctex.gz"))

# compile from a fresh copy of the LaTeX folder
with tempfile.TemporaryDirectory() as tmp:
    t = Path(tmp) / "pkg"
    shutil.copytree(SRC, t)
    r = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main.tex"],
                       cwd=t, capture_output=True, text=True)
    log = (t / "main.log").read_text(errors="ignore") if (t / "main.log").exists() else ""
    errs = [l for l in log.splitlines() if l.startswith("!")]
    if r.returncode != 0 or errs:
        print("BUILD FAILED:", errs[:3] or r.stdout[-800:])
        if FINAL and any("Unresolved author item" in e for e in errs):
            print("-> author items ([PENDING]/[TBD]) are still open; fill them in main.tex, then rerun with --final.")
        sys.exit(1)
    shutil.copy2(t / "main.pdf", OUT / "main.pdf")
    shutil.copy2(t / "main.bbl", SRC / "main.bbl")
    undefined = len(re.findall(r"undefined", log, re.I))
    pages = re.search(r"Output written on main\.pdf \((\d+) pages", log)

# Overleaf: New Project > Upload Project accepts this zip; main.tex compiles with pdfLaTeX
shutil.make_archive(str(OUT / "LaTeX_source_for_Overleaf"), "zip", SRC)
n_inc = len(re.findall("@", (M / "included_studies.bib").read_text()))
(OUT / "FILE_LIST.md").write_text(f"""# Submission package: Artificial Intelligence Review

Build mode: {"FINAL (no author items left)" if FINAL else "CHECK (author-item boxes still visible; not for upload)"}

Prepared as the Springer Nature LaTeX template user manual (v3.1, December 2024) asks: template class and reference
style unchanged, no custom fonts or added formatting, figures at the same level as the .tex file, single line spacing.

| File | Content |
|---|---|
| `LaTeX_source/main.tex` | Manuscript, single LaTeX file (Springer Nature template v3.1, `sn-jnl`, `sn-basic`) |
| `LaTeX_source/main.bbl` | Compiled bibliography (include when uploading LaTeX source) |
| `LaTeX_source/references.bib`, `included_studies.bib` | Bibliography sources: background references and the {n_inc} included studies |
| `LaTeX_source/sn-jnl.cls`, `sn-basic.bst` | Springer Nature class and reference style (December 2024 package, unchanged) |
| `LaTeX_source/fig01_*.pdf` ... `fig11_*.pdf` | {len(figs)} vector figures (PDF, RGB), in order of appearance |
| `Supplementary_Material/` | S1-S6 (search strategy, PRISMA checklist, extraction database and codebook, quality assessment, protocol, screening and eligibility decisions) |
| `main.pdf` | PDF compiled from `LaTeX_source/` alone ({pages.group(1) if pages else '?'} pages; undefined references: {undefined}) |

Overleaf: `LaTeX_source_for_Overleaf.zip` is the same folder zipped (New Project > Upload Project; compiler pdfLaTeX, main
document main.tex). After editing on Overleaf, Overleaf holds the master copy: the workspace scripts regenerate numbers
and tables in SLR_Workspace/manuscript/main.tex, not in the Overleaf project.

Upload: every file in `LaTeX_source/` as manuscript source (main.tex as the main document), the files in
`Supplementary_Material/` as supplementary material, and `main.pdf` for reference if the system asks for one.
""")
print(f"{'FINAL' if FINAL else 'CHECK'} package -> {OUT} ({len(figs)} figures; compiled, {pages.group(1) if pages else '?'} pages, "
      f"undefined references: {undefined})")
