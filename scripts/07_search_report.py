"""Generate the search documentation from the logged runs (PRISMA 2020 item 7 / supplementary S1).

Inputs : stageB/search_runs.csv, stageB/records_all.csv, stageB/records_unique.csv, stageB/recall_check.txt
Outputs: logs/search_report.md                      human-readable report (strings, dates, hits, recall)
         manuscript/generated/search_table.tex      LaTeX table for the manuscript (counts from data)
"""
import csv
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
B = Path(__file__).resolve().parent.parent / "stageB"
LOGS = Path(__file__).resolve().parent.parent / "logs"
GEN = Path(__file__).resolve().parent.parent / "manuscript" / "generated"
GEN.mkdir(parents=True, exist_ok=True)

runs = list(csv.DictReader(open(B / "search_runs.csv")))
allrecs = list(csv.DictReader(open(B / "records_all.csv")))
uniq = list(csv.DictReader(open(B / "records_unique.csv")))
recall = (B / "recall_check.txt").read_text()

FINAL = {"OA-Q1v2", "OA-Q2v2", "OA-Q3v2", "S2-Q1"}
is_final = lambda r: r["query_id"] in FINAL or r["source"] == "arXiv"
PILOT = {"OA-Q1", "OA-Q2"}

retrieved_by_source = Counter(r["source"] for r in allrecs)
n_all, n_uniq = len(allrecs), len(uniq)
n_in_A = sum(bool(u["in_stageA"]) for u in uniq)
dates = sorted({r["date"] for r in runs})

# ---------- markdown ----------
md = ["# Search Report (generated by scripts/07_search_report.py — do not edit by hand)", "",
      f"Search dates: {', '.join(dates)}. **Search conducted up to {dates[-1]}.**", "",
      "## 1. Final search strategy (v2)", ""]
for r in runs:
    if r["source"] == "OpenAlex" and r["query_id"] in FINAL:
        md += [f"**{r['query_id']}** (OpenAlex, `{r['query'].split(':', 1)[0]}`; all years, all document types) "
               f"— hits: **{r['hits_reported']}**, retrieved: {r['records_retrieved']}", "", "```",
               r["query"].split(":", 1)[1].strip(), "```", ""]
s2 = [r for r in runs if r["source"] == "SemScholar"]
for r in s2:
    md += [f"**{r['query_id']}** (Semantic Scholar bulk search) — hits: **{r['hits_reported']}**, "
           f"retrieved: {r['records_retrieved']} ({r['note']})", "", "```", r["query"], "```", ""]
ax = [r for r in runs if r["source"] == "arXiv"]
ax_hits = sum(int(r["hits_reported"]) for r in ax)
md += [f"**arXiv** — {len(ax)} phrase-combination queries on abstracts "
       f"(`abs:<Safe-RL phrase> AND abs:<vehicle phrase>` and "
       f"`abs:\"reinforcement learning\" AND abs:<mechanism phrase> AND abs:<vehicle phrase>`); "
       f"summed hits **{ax_hits}**, unique arXiv records **{retrieved_by_source['arXiv']}**. "
       "Per-query strings and counts: `stageB/search_runs.csv`.", ""]
md += ["## 2. Sources attempted but not usable", "",
       "| Source | Date | Outcome |", "|---|---|---|"]
for r in runs:
    if r["records_retrieved"] == "0" and r["source"] in ("DBLP",):
        md.append(f"| {r['source']} | {r['date']} | {r['note']} |")
md += ["| IEEE Xplore, Scopus, Web of Science, ScienceDirect, SpringerLink, ACM DL | — | "
       "No open API; strings provided in `logs/search_strings.md` for execution via institutional access |", ""]
md += ["## 3. Search development (pilot, v1) and recall validation", "",
       "Pilot strings (v1) were run first and validated against the Stage A records already judged relevant "
       "(a known-relevant reference set). Missed records were inspected and the concept blocks extended "
       "(safe multi-agent RL; racing, parking, platooning, connected vehicles, driving policy, kinematic bicycle "
       "model, lane change, ACC, car-following, merging, unsignalized intersection; safety constraint/guarantee) "
       "and a title-only query (Q3) was added to compensate for missing abstracts in OpenAlex.", "",
       "| Query | Version | Hits |", "|---|---|---|"]
for r in runs:
    if r["source"] == "OpenAlex":
        md.append(f"| {r['query_id']} | {'pilot v1 (superseded)' if r['query_id'] in PILOT else 'final v2'} | {r['hits_reported']} |")
md += ["", "Recall of the final strategy (from `stageB/recall_check.txt`):", "", "```", recall.strip(), "```", ""]
md += ["## 4. Records flow (database searches)", "",
       "| Step | Count |", "|---|---|"]
for s, c in sorted(retrieved_by_source.items()):
    md.append(f"| Records retrieved — {s} | {c} |")
md += [f"| **Records retrieved — total** | **{n_all}** |",
       f"| Duplicates removed within database results | {n_all - n_uniq} |",
       f"| Unique database records | {n_uniq} |",
       f"| … of which already in Stage A (seed corpus) | {n_in_A} |",
       f"| **New records to screen** | **{n_uniq - n_in_A}** |", ""]
(LOGS / "search_report.md").write_text("\n".join(md) + "\n")

# ---------- LaTeX table ----------
def tex(s):
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


oa = {r["query_id"]: r for r in runs if r["source"] == "OpenAlex"}
rows = [("OpenAlex", "Q1: [S] AND [V]", "title+abstract", oa["OA-Q1v2"]["hits_reported"]),
        ("OpenAlex", "Q2: [R] AND [M] AND [V]", "title+abstract", oa["OA-Q2v2"]["hits_reported"]),
        ("OpenAlex", "Q3: RL AND safety terms AND vehicle terms", "title", oa["OA-Q3v2"]["hits_reported"])]
rows += [("Semantic Scholar", "[S] AND [V] (abridged)", "title+abstract", r["hits_reported"]) for r in s2]
rows += [("arXiv", f"{len(ax)} phrase combinations of [S]/[M] with [V]", "abstract", f"{ax_hits} ({retrieved_by_source['arXiv']} unique)")]
lines = [r"\begin{table}[ht]",
         r"\caption{Database searches (final strategy). Concept blocks: [S] Safe RL terms, [V] vehicle terms, [R] ``reinforcement learning'', [M] safety/control-mechanism terms; full strings in Supplementary Table S1}\label{tab:search}",
         r"\footnotesize", r"\begin{tabularx}{\textwidth}{@{}llLr@{}}", r"\toprule",
         r"Source & Query & Fields & Hits \\", r"\midrule"]
lines += [f"{tex(a)} & {tex(b)} & {tex(c)} & {tex(str(d))} \\\\" for a, b, c, d in rows]
lines += [r"\midrule",
          f"\\multicolumn{{3}}{{@{{}}l}}{{Records retrieved (all database queries)}} & {n_all} \\\\",
          f"\\multicolumn{{3}}{{@{{}}l}}{{Duplicates removed across database results}} & {n_all - n_uniq} \\\\",
          f"\\multicolumn{{3}}{{@{{}}l}}{{Unique database records (of which in seed corpus: {n_in_A})}} & {n_uniq} \\\\",
          r"\botrule", r"\end{tabularx}", r"\end{table}"]
(GEN / "search_table.tex").write_text("\n".join(lines) + "\n")
print((LOGS / "search_report.md").read_text()[-900:])
print("wrote", GEN / "search_table.tex")
